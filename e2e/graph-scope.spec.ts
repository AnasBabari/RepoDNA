import { readFileSync } from 'node:fs';
import { expect, test } from '@playwright/test';
import type { RepoDNAProjectV2 } from '../app/lib/analyzer/v2/types';
import { graphCounts, recordedGraphScope } from '../app/lib/graph-scope';
import { openExportDialog } from './helpers/app-driver';

const sample = JSON.parse(readFileSync('public/samples/nanogpt.json', 'utf8')) as RepoDNAProjectV2;
for (const legacy of [false, true]) test(`compacted ${legacy ? 'legacy' : 'recorded'} scope agrees in UI and download`, async ({ page, context, baseURL }) => {
  const project = structuredClone(sample);
  project.edges = project.edges.filter((edge) => edge.target && edge.status === 'resolved').slice(0, 3);
  project.unresolved = [];
  project.completeness = { status: 'FULLY_MAPPED', reasons: [] };
  project.coverage.truncationReasons = ['GRAPH_EDGES_COMPACTED'];
  project.graphScope = recordedGraphScope({ nodes: 200, relationships: 1000, unresolvedRelationships: 900, ambiguousRelationships: 12 }, graphCounts(project));
  if (legacy) delete project.graphScope;
  await context.route('**/*', (route) => baseURL && route.request().url().startsWith(baseURL) ? route.continue() : route.abort());
  await page.route('**/samples/nanogpt.json', (route) => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(project) }));
  await page.goto('/?repo=https://github.com/karpathy/nanoGPT');
  const expected = legacy ? 'unknown' : '900';
  await expect(page.getByRole('region', { name: 'Graph scope', exact: true })).toContainText(`Whole-analysis resolution gaps: ${expected}; retained gaps: 0`);
  await expect(page.getByRole('region', { name: 'Plain-language summary' })).toContainText('Coverage limited');
  await expect(page.getByRole('region', { name: 'Scan coverage', exact: true })).toContainText(legacy ? 'Unknown (0 retained)' : '900');
  await page.getByRole('button', { name: 'Technical', exact: false }).click();
  await expect(page.getByRole('region', { name: 'Scan coverage details' })).toContainText(legacy ? 'Unknown (0 retained)' : '900');
  await openExportDialog(page);
  const dialog = page.getByRole('dialog', { name: 'Export graph' });
  await expect(dialog).toContainText('Export all retained graph findings.');
  await expect(dialog).not.toContainText('Export full dependency graph');
  const scope = dialog.getByRole('region', { name: 'Graph scope', exact: true });
  await expect(scope).toContainText(`Whole-analysis resolution gaps: ${expected}; retained gaps: 0`);
  await scope.locator('summary').click();
  await expect(scope.getByRole('row', { name: /^Relationships / })).toContainText(legacy ? 'unknown' : '997');
  const pending = page.waitForEvent('download');
  await dialog.getByRole('button', { name: 'Export Graph JSON', exact: true }).click();
  const json = JSON.parse(readFileSync((await (await pending).path())!, 'utf8'));
  expect(json.manifest.graphScope.original.unresolvedRelationships).toBe(legacy ? null : 900);
  expect(json.manifest.graphScope.retained.unresolvedRelationships).toBe(0);
  expect(json.manifest.graphScope.analyticsScope).toBe('retained-subgraph');
  const pendingTxt = page.waitForEvent('download');
  await dialog.getByRole('button', { name: 'Export TXT', exact: true }).click();
  expect(readFileSync((await (await pendingTxt).path())!, 'utf8')).toContain(`Whole-analysis resolution gaps: ${expected}`);
});
